from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Table, TableStyle, Spacer
from reportlab.lib.units import inch
from datetime import datetime
import os

def generate_pdf_report(user, readings, summary_text: str) -> str:
    filename = f"healthping_report_{user.phone[-4:]}_{datetime.now().strftime('%Y%m%d')}.pdf"
    filepath = os.path.join("reports", filename)
    os.makedirs("reports", exist_ok=True)

    doc = SimpleDocTemplate(filepath, pagesize=A4,
                            rightMargin=40, leftMargin=40,
                            topMargin=40, bottomMargin=40)

    styles = getSampleStyleSheet()
    elements = []

    # Header
    title_style = ParagraphStyle(
        'Title',
        parent=styles['Heading1'],
        fontSize=24,
        textColor=colors.HexColor('#2E86AB'),
        spaceAfter=5
    )
    subtitle_style = ParagraphStyle(
        'Subtitle',
        parent=styles['Normal'],
        fontSize=11,
        textColor=colors.HexColor('#666666'),
        spaceAfter=20
    )

    elements.append(Paragraph("HealthPing", title_style))
    elements.append(Paragraph("Weekly Health Report", subtitle_style))

    # Patient info box
    info_data = [
        ["Patient Name", user.name or "N/A", "Condition", user.condition or "N/A"],
        ["Medicines", user.medicines or "N/A", "Report Date", datetime.now().strftime("%d %b %Y")],
    ]
    info_table = Table(info_data, colWidths=[1.2*inch, 2.3*inch, 1.2*inch, 2.3*inch])
    info_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (0,-1), colors.HexColor('#2E86AB')),
        ('BACKGROUND', (2,0), (2,-1), colors.HexColor('#2E86AB')),
        ('TEXTCOLOR', (0,0), (0,-1), colors.white),
        ('TEXTCOLOR', (2,0), (2,-1), colors.white),
        ('FONTNAME', (0,0), (-1,-1), 'Helvetica'),
        ('FONTSIZE', (0,0), (-1,-1), 10),
        ('PADDING', (0,0), (-1,-1), 8),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#DDDDDD')),
        ('ROWBACKGROUNDS', (1,0), (3,-1), [colors.HexColor('#F8F9FA'), colors.white]),
    ]))
    elements.append(info_table)
    elements.append(Spacer(1, 20))

    # Readings table
    elements.append(Paragraph("📊 This Week's Readings", styles['Heading2']))
    elements.append(Spacer(1, 10))

    table_data = [["Date", "Blood Sugar (mg/dL)", "BP (mmHg)", "Weight (kg)", "Notes"]]

    for r in readings:
        date_str = r.created_at.strftime("%d %b %Y")
        sugar = str(r.sugar) if r.sugar else "-"
        bp = f"{r.bp_systolic}/{r.bp_diastolic}" if r.bp_systolic else "-"
        weight = str(r.weight) if r.weight else "-"
        notes = r.notes[:30] if r.notes else "-"

        # Highlight danger values
        row = [date_str, sugar, bp, weight, notes]
        table_data.append(row)

    readings_table = Table(table_data, colWidths=[1.2*inch, 1.5*inch, 1.3*inch, 1.2*inch, 1.8*inch])
    
    table_style = [
        ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#2E86AB')),
        ('TEXTCOLOR', (0,0), (-1,0), colors.white),
        ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
        ('FONTSIZE', (0,0), (-1,-1), 9),
        ('PADDING', (0,0), (-1,-1), 8),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#DDDDDD')),
        ('ROWBACKGROUNDS', (0,1), (-1,-1), [colors.white, colors.HexColor('#F8F9FA')]),
        ('ALIGN', (0,0), (-1,-1), 'CENTER'),
    ]

    # Highlight high sugar in red
    for i, r in enumerate(readings, 1):
        if r.sugar and r.sugar >= 250:
            table_style.append(('BACKGROUND', (1,i), (1,i), colors.HexColor('#FFE5E5')))
            table_style.append(('TEXTCOLOR', (1,i), (1,i), colors.HexColor('#CC0000')))
        if r.bp_systolic and r.bp_systolic >= 160:
            table_style.append(('BACKGROUND', (2,i), (2,i), colors.HexColor('#FFE5E5')))
            table_style.append(('TEXTCOLOR', (2,i), (2,i), colors.HexColor('#CC0000')))

    readings_table.setStyle(TableStyle(table_style))
    elements.append(readings_table)
    elements.append(Spacer(1, 20))

    # AI Summary
    elements.append(Paragraph("🤖 AI Health Summary", styles['Heading2']))
    elements.append(Spacer(1, 10))
    summary_style = ParagraphStyle(
        'Summary',
        parent=styles['Normal'],
        fontSize=10,
        leading=16,
        textColor=colors.HexColor('#333333')
    )
    clean_summary = summary_text.replace("*", "").replace("#", "")
    elements.append(Paragraph(clean_summary, summary_style))
    elements.append(Spacer(1, 20))

    # Footer
    footer_style = ParagraphStyle(
        'Footer',
        parent=styles['Normal'],
        fontSize=8,
        textColor=colors.HexColor('#999999'),
        alignment=1
    )
    elements.append(Paragraph(
        "Generated by HealthPing | This report is for personal tracking only, not a medical diagnosis.",
        footer_style
    ))

    doc.build(elements)
    return filepath